const REAL_POPULATIONS = Object.freeze({
  arg: 45808747,
  bra: 212583750,
  chn: 1409670000,
  rus: 143957079,
  usa: 340110988,
});

const TRAIT_OVERRIDES = Object.freeze({
  arg: 'agri_power', bra: 'agri_power', chn: 'tech_giant', isr: 'military_tradition',
  jpn: 'tech_giant', kor: 'tech_giant', rus: 'military_tradition', sau: 'oil_rich',
  che: 'financial_hub', sgp: 'financial_hub', ven: 'oil_rich',
});
const GENERIC_TRAITS = Object.freeze(['oil_rich', 'military_tradition', 'tech_giant', 'agri_power', 'financial_hub']);

function hash(value) {
  return [...value].reduce((total, character) => ((total * 31) + character.charCodeAt(0)) >>> 0, 2166136261);
}

function clamp(value, minimum, maximum) {
  return Math.min(maximum, Math.max(minimum, value));
}

function traitForCountry(id) {
  return TRAIT_OVERRIDES[id] ?? GENERIC_TRAITS[hash(id) % GENERIC_TRAITS.length];
}

function resourcesForCountry(country) {
  const seed = hash(country.id);
  const areaFactor = Math.max(1, Math.round(country.area_km2 / 10_000));
  const uraniumRich = new Set(['aus', 'bra', 'can', 'kaz', 'nam', 'ner', 'rus', 'usa']);
  const rareEarthRich = new Set(['aus', 'bra', 'chn', 'ind', 'rus', 'vnm']);
  return {
    steel: (areaFactor * 1_100) + ((seed >>> 4) % 80_000),
    uranium: uraniumRich.has(country.id) ? 8_000 + ((seed >>> 9) % 28_000) : (seed % 2_500),
    rare_earths: rareEarthRich.has(country.id) ? 5_000 + ((seed >>> 12) % 20_000) : ((seed >>> 6) % 1_400),
  };
}

export const COUNTRIES = Object.freeze(COUNTRY_SEED.map((country) => Object.freeze({ ...country, trait: traitForCountry(country.id), ...resourcesForCountry(country) })));

export function validateCountries(countries) {
  if (!Array.isArray(countries) || countries.length !== 200) {
    throw new Error('O seed deve conter exatamente 200 paises.');
  }

  const ids = new Set();
  for (const country of countries) {
    if (!country?.id || !country.nome || !country.trait || !Number.isFinite(country.area_km2) || country.area_km2 <= 0 || !Number.isFinite(country.uranium) || !Number.isFinite(country.steel) || !Number.isFinite(country.rare_earths)) {
      throw new Error('Cada pais precisa de id, nome, trait, recursos e area positiva.');
    }
    if (ids.has(country.id)) {
      throw new Error(`ID de pais duplicado: ${country.id}`);
    }
    ids.add(country.id);
  }
}

export function getCountryById(id) {
  return COUNTRIES.find((country) => country.id === id) ?? null;
}

export function createCountryProfile(country) {
  if (!country) {
    throw new Error('Pais invalido.');
  }

  const seed = hash(country.id);
  const density = 12 + (seed % 240);
  const populacao_base = REAL_POPULATIONS[country.id]
    ?? clamp(Math.round(country.area_km2 * density), 25_000, 1_450_000_000);
  const pibPerCapita = 3_500 + ((seed >>> 8) % 57_000);

  return {
    ...country,
    populacao: populacao_base,
    populacao_base,
    pib_base: populacao_base * pibPerCapita,
    bioma_dominante: BIOMES[(seed >>> 16) % BIOMES.length],
    tipo_governo: GOVERNMENTS[(seed >>> 20) % GOVERNMENTS.length],
  };
}

